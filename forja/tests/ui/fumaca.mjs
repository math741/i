import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const RAIZ = path.resolve(import.meta.dirname, '../..');
const srv = spawn(path.join(RAIZ, 'build/forja_server'), ['--porta', '8798', '--cliente', path.join(RAIZ, 'client'), '--dados', path.join(RAIZ, 'run/fumaca/saves'), '--logs', path.join(RAIZ, 'run/fumaca/logs')], { stdio: 'inherit' });
await new Promise((r) => setTimeout(r, 400));
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const erros = [];
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') erros.push(m.type() + ': ' + m.text()); });
p.on('pageerror', (e) => erros.push('pageerror: ' + e.message));
await p.goto('http://127.0.0.1:8798/?nome=Teste');
await p.waitForTimeout(2500);
await p.click('[data-testid=criar-sala]');
await p.waitForTimeout(800);
await p.click('[data-testid=treino]');
await p.waitForTimeout(2500);
await p.screenshot({ path: path.join(RAIZ, 'run/fumaca/arena.png') });
await p.click('[data-testid=abrir-oficina]');
await p.waitForTimeout(1500);
await p.screenshot({ path: path.join(RAIZ, 'run/fumaca/oficina.png') });
console.log('erros:', erros.length ? erros.join('\n') : 'nenhum');
console.log('fps:', await p.evaluate(() => window.forja.cena.stats.fps));
await b.close();
srv.kill();
